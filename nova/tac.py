"""
nova.tac - Module 4: three-address code, generated by an SDT scheme with
backpatching.

Boolean expressions are compiled as *jumping code* (short-circuit), so
`a > 0 and b(x) > 0` never evaluates `b(x)` when `a <= 0`.  The jump targets are
not known when the jump is emitted, so they are left blank and filled in later -
that is exactly `makelist / merge / backpatch` from the book, and every patch is
written to `patch_log` so the viewer can show it happening.

A `case` statement is lowered to a genuine jump table (`jtab`), not a chain of
comparisons, when the labels are dense enough to make that worthwhile.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

from . import ast_nodes as A
from .semantic import BOOL, INT, STR, SemanticAnalyzer

RELOPS = {"<": "iflt", ">": "ifgt", "<=": "ifle", ">=": "ifge",
          "==": "ifeq", "!=": "ifne"}
ARITH = {"+", "-", "*", "/", "%"}


@dataclass
class Quad:
    """One three-address instruction:  (op, arg1, arg2, result)."""
    op: str
    a: Optional[str] = None
    b: Optional[str] = None
    r: object = None                       # name, jump target (int), or table

    def copy(self) -> "Quad":
        return Quad(self.op, self.a, self.b,
                    list(self.r) if isinstance(self.r, list) else self.r)


@dataclass
class IRFunction:
    name: str
    params: List[str]
    code: List[Quad] = field(default_factory=list)
    n_temps: int = 0
    ret_type: str = "void"

    def targets(self) -> Dict[int, str]:
        """Every instruction index that some jump points at, given a label name."""
        tset = set()
        for q in self.code:
            if q.op == "goto" or q.op.startswith("if"):
                if isinstance(q.r, int):
                    tset.add(q.r)
            elif q.op == "jtab":
                for _, t in q.b:
                    tset.add(t)
                tset.add(q.r)
        labels = {}
        for i, t in enumerate(sorted(tset)):
            labels[t] = f"L{i}"
        return labels

    def listing(self) -> List[str]:
        labels = self.targets()
        out = []
        for i, q in enumerate(self.code):
            lab = labels.get(i, "")
            out.append(f"{i:>3}  {lab:<5} {fmt(q, labels)}")
        if len(self.code) in labels:
            out.append(f"{len(self.code):>3}  {labels[len(self.code)]:<5} (end)")
        return out


def fmt(q: Quad, labels: Optional[Dict[int, str]] = None) -> str:
    L = (lambda t: labels.get(t, str(t))) if labels else (lambda t: str(t))
    op = q.op
    if op == "=":
        return f"{q.r} = {q.a}"
    if op in ARITH:
        return f"{q.r} = {q.a} {op} {q.b}"
    if op == "uminus":
        return f"{q.r} = - {q.a}"
    if op == "goto":
        return f"goto {L(q.r)}"
    if op.startswith("if"):
        sym = {"iflt": "<", "ifgt": ">", "ifle": "<=", "ifge": ">=",
               "ifeq": "==", "ifne": "!="}[op]
        return f"if {q.a} {sym} {q.b} goto {L(q.r)}"
    if op == "param":
        return f"param {q.a}"
    if op == "call":
        return (f"{q.r} = call {q.a}, {q.b}" if q.r else f"call {q.a}, {q.b}")
    if op == "ret":
        return f"return {q.a}" if q.a is not None else "return"
    if op == "print":
        return f"print {q.a}"
    if op == "jtab":
        cases = " ".join(f"{v}->{L(t)}" for v, t in q.b)
        return f"jumptable {q.a} [{cases}] default {L(q.r)}"
    return f"{op} {q.a} {q.b} {q.r}"


# ==========================================================================
class TACGen:
    def __init__(self, sema: SemanticAnalyzer):
        self.sema = sema
        self.code: List[Quad] = []
        self.temp_n = 0
        self.patch_log: List[str] = []
        self.functions: Dict[str, IRFunction] = {}

    # ------------------------------------------------------------ machinery
    def emit(self, op, a=None, b=None, r=None) -> int:
        self.code.append(Quad(op, a, b, r))
        return len(self.code) - 1

    @property
    def nextquad(self) -> int:
        return len(self.code)

    def newtemp(self) -> str:
        t = f"t{self.temp_n}"
        self.temp_n += 1
        return t

    @staticmethod
    def makelist(i: int) -> List[int]:
        return [i]

    @staticmethod
    def merge(*lists: Sequence[int]) -> List[int]:
        out: List[int] = []
        for l in lists:
            out.extend(l)
        return out

    def backpatch(self, lst: Sequence[int], target: int) -> None:
        if not lst:
            return
        for i in lst:
            self.code[i].r = target
        self.patch_log.append(
            f"backpatch({{{', '.join(str(i) for i in sorted(lst))}}}, {target})")

    # -------------------------------------------------------------- driver
    def generate(self, prog: A.Program) -> Dict[str, IRFunction]:
        for f in prog.funcs:
            self.code, self.temp_n = [], 0
            for st in f.body:
                nxt = self.statement(st)
                self.backpatch(nxt, self.nextquad)
            if not self.code or self.code[-1].op != "ret":
                self.emit("ret", None)
            info = self.sema.functions[f.name]
            self.functions[f.name] = IRFunction(
                f.name, list(f.params), self.code, self.temp_n, info.ret)

        self.code, self.temp_n = [], 0
        for st in prog.main:
            nxt = self.statement(st)
            self.backpatch(nxt, self.nextquad)
        self.emit("ret", None)
        self.functions["main"] = IRFunction("main", [], self.code, self.temp_n, "void")
        return self.functions

    # ---------------------------------------------------------- statements
    def statements(self, body: List[A.Node]) -> List[int]:
        nxt: List[int] = []
        for st in body:
            self.backpatch(nxt, self.nextquad)
            nxt = self.statement(st)
        return nxt

    def statement(self, node) -> List[int]:
        """Returns S.nextlist - the jumps that must land after this statement."""
        if isinstance(node, A.Let) or isinstance(node, A.Assign):
            sym = getattr(node, "sym", None)
            name = sym.ir_name if sym else node.name
            self.assign_into(name, node.expr)
            return []

        if isinstance(node, A.Print):
            place = self.rvalue(node.expr)
            self.emit("print", place)
            return []

        if isinstance(node, A.Return):
            place = self.rvalue(node.expr)
            self.emit("ret", place)
            return []

        if isinstance(node, A.CallStmt):
            self.call(node, want_result=False)
            return []

        if isinstance(node, A.If):
            t, f = self.bool_expr(node.cond)
            self.backpatch(t, self.nextquad)
            s1 = self.statements(node.then_body)
            if not node.else_body:
                return self.merge(f, s1)
            n = self.makelist(self.emit("goto", r=None))
            self.backpatch(f, self.nextquad)
            s2 = self.statements(node.else_body)
            return self.merge(s1, n, s2)

        if isinstance(node, A.While):
            begin = self.nextquad
            t, f = self.bool_expr(node.cond)
            self.backpatch(t, self.nextquad)
            s = self.statements(node.body)
            self.backpatch(s, begin)
            self.emit("goto", r=begin)
            return f

        if isinstance(node, A.Case):
            return self.case_stmt(node)

        return []

    def case_stmt(self, node: A.Case) -> List[int]:
        sel = self.rvalue(node.expr)
        table: List[Tuple[int, int]] = []
        jt = self.emit("jtab", sel, table, None)
        exits: List[int] = []
        for clause in node.clauses:
            start = self.nextquad
            table.append((clause.value, start))
            nxt = self.statements(clause.body)
            self.backpatch(nxt, self.nextquad)
            exits.append(self.emit("goto", r=None))
        default = self.nextquad
        self.code[jt].r = default
        if node.otherwise:
            nxt = self.statements(node.otherwise)
            self.backpatch(nxt, self.nextquad)
        self.patch_log.append(
            f"jump table for 'case' filled with {len(table)} label(s), "
            f"default -> {default}")
        return exits

    # ------------------------------------------------------------- helpers
    def assign_into(self, name: str, expr) -> None:
        if expr.type == BOOL and not isinstance(expr, A.Bool):
            self.materialise(expr, name)
        else:
            self.rvalue(expr, target=name)

    def materialise(self, expr, target: str) -> None:
        """Turn jumping code back into a 0/1 value stored in `target`."""
        t, f = self.bool_expr(expr)
        self.backpatch(t, self.nextquad)
        self.emit("=", "1", None, target)
        skip = self.makelist(self.emit("goto", r=None))
        self.backpatch(f, self.nextquad)
        self.emit("=", "0", None, target)
        self.backpatch(skip, self.nextquad)

    # ------------------------------------------------------- r-value coding
    def rvalue(self, node, target: Optional[str] = None) -> str:
        """Generate code that leaves the value of `node` in a name; return it."""
        if isinstance(node, A.Num):
            if target:
                self.emit("=", str(node.value), None, target)
                return target
            return str(node.value)
        if isinstance(node, A.Str):
            lit = '"' + node.value + '"'
            if target:
                self.emit("=", lit, None, target)
                return target
            return lit
        if isinstance(node, A.Bool):
            v = "1" if node.value else "0"
            if target:
                self.emit("=", v, None, target)
                return target
            return v
        if isinstance(node, A.Var):
            sym = getattr(node, "sym", None)
            name = sym.ir_name if sym else node.name
            if target:
                self.emit("=", name, None, target)
                return target
            return name
        if isinstance(node, A.Unary):
            if node.op == "-":
                a = self.rvalue(node.operand)
                r = target or self.newtemp()
                self.emit("uminus", a, None, r)
                return r
            r = target or self.newtemp()
            self.materialise(node, r)
            return r
        if isinstance(node, A.Binary):
            if node.op in ARITH:
                a = self.rvalue(node.left)
                b = self.rvalue(node.right)
                r = target or self.newtemp()
                self.emit(node.op, a, b, r)
                return r
            r = target or self.newtemp()
            self.materialise(node, r)
            return r
        if isinstance(node, A.Call):
            return self.call(node, want_result=True, target=target)
        return "0"

    def call(self, node, want_result: bool, target: Optional[str] = None) -> str:
        places = [self.rvalue(a) for a in node.args]
        for p in places:
            self.emit("param", p)
        if want_result:
            r = target or self.newtemp()
            self.emit("call", node.name, str(len(places)), r)
            return r
        self.emit("call", node.name, str(len(places)), None)
        return ""

    # ------------------------------------------------- boolean jumping code
    def bool_expr(self, node) -> Tuple[List[int], List[int]]:
        """Returns (truelist, falselist) - the classic B.true / B.false."""
        if isinstance(node, A.Bool):
            if node.value:
                return self.makelist(self.emit("goto", r=None)), []
            return [], self.makelist(self.emit("goto", r=None))

        if isinstance(node, A.Binary) and node.op == "and":
            t1, f1 = self.bool_expr(node.left)
            self.backpatch(t1, self.nextquad)          # B1.true -> start of B2
            t2, f2 = self.bool_expr(node.right)
            return t2, self.merge(f1, f2)

        if isinstance(node, A.Binary) and node.op == "or":
            t1, f1 = self.bool_expr(node.left)
            self.backpatch(f1, self.nextquad)          # B1.false -> start of B2
            t2, f2 = self.bool_expr(node.right)
            return self.merge(t1, t2), f2

        if isinstance(node, A.Unary) and node.op == "not":
            t, f = self.bool_expr(node.operand)
            return f, t                                 # simply swap the lists

        if isinstance(node, A.Binary) and node.op in RELOPS:
            a = self.rvalue(node.left)
            b = self.rvalue(node.right)
            tl = self.makelist(self.emit(RELOPS[node.op], a, b, None))
            fl = self.makelist(self.emit("goto", r=None))
            return tl, fl

        # a bool-valued variable or call: test it against 0
        place = self.rvalue(node)
        tl = self.makelist(self.emit("ifne", place, "0", None))
        fl = self.makelist(self.emit("goto", r=None))
        return tl, fl
